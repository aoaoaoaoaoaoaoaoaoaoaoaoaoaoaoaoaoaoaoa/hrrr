//! HRRR-owned wind-quill die forged under the shared Poolrooms universe.

use brass_foundry::{Charge, Model, RustReach, Vec3 as V3, Vertex, emit_rust, forge};
use std::{
    f32::consts::TAU,
    fs::File,
    io::{self, BufWriter, Write},
    path::Path,
};

pub(crate) const POSE_COUNT: usize = 64;

pub(crate) fn bake(path: &Path) -> io::Result<()> {
    let die = die();
    let mut out = BufWriter::new(File::create(path)?);
    writeln!(out, "// @generated by build/wind_quill.rs; do not edit.")?;
    writeln!(out, "pub(super) const POSE_COUNT: usize = {POSE_COUNT};")?;
    for pose in 0..POSE_COUNT {
        let angle = TAU * pose as f32 / POSE_COUNT as f32;
        let model = die.transformed(
            |point| point.rotate_z(angle),
            |normal| normal.rotate_z(angle),
        );
        emit_rust(
            &mut out,
            &format!("QUILL_{pose:02}"),
            &forge(&model, Charge::Darkened(0.88)),
            RustReach::Module,
        )?;
    }
    writeln!(out, "pub(super) static QUILL: [ForgedMesh; POSE_COUNT] = [")?;
    for pose in 0..POSE_COUNT {
        writeln!(out, "QUILL_{pose:02},")?;
    }
    writeln!(out, "];")
}

fn die() -> Model {
    const RISE: f32 = 0.58;
    const CROWN_SCALE: f32 = 0.88;
    const OUTLINE: [V3; 12] = [
        V3::new(0.0, -7.2, 0.0),
        V3::new(3.25, -2.0, 0.0),
        V3::new(1.05, -2.0, 0.0),
        V3::new(1.05, 3.15, 0.0),
        V3::new(3.0, 2.15, 0.0),
        V3::new(1.55, 5.85, 0.0),
        V3::new(0.0, 4.55, 0.0),
        V3::new(-1.55, 5.85, 0.0),
        V3::new(-3.0, 2.15, 0.0),
        V3::new(-1.05, 3.15, 0.0),
        V3::new(-1.05, -2.0, 0.0),
        V3::new(-3.25, -2.0, 0.0),
    ];
    let crown = OUTLINE.map(|point| V3::new(point.x * CROWN_SCALE, point.y * CROWN_SCALE, RISE));
    let mut model = Model::default();
    for edge in 0..OUTLINE.len() {
        let next = (edge + 1) % OUTLINE.len();
        let normal = (OUTLINE[next] - OUTLINE[edge])
            .cross(crown[edge] - OUTLINE[edge])
            .normalized();
        model.quad([
            Vertex::new(OUTLINE[edge], normal),
            Vertex::new(OUTLINE[next], normal),
            Vertex::new(crown[next], normal),
            Vertex::new(crown[edge], normal),
        ]);
    }
    let center = Vertex::new(V3::new(0.0, 0.0, RISE), V3::new(0.0, 0.0, 1.0));
    for edge in 0..crown.len() {
        let next = (edge + 1) % crown.len();
        model.triangle(
            center,
            Vertex::new(crown[edge], center.normal),
            Vertex::new(crown[next], center.normal),
        );
    }
    model
}
