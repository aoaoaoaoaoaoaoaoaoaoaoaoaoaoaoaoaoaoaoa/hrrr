//! HRRR-owned wind-barb dies forged under the shared Poolrooms universe.

use brass_foundry::{Charge, Model, RustReach, Vec3 as V3, Vertex, emit_rust, forge};
use std::{
    f32::consts::TAU,
    fs::File,
    io::{self, BufWriter, Write},
    path::Path,
};

pub(crate) const POSE_COUNT: usize = 64;

pub(crate) fn bake(path: &Path) -> io::Result<()> {
    let mut out = BufWriter::new(File::create(path)?);
    writeln!(out, "// @generated by build/wind_barb.rs; do not edit.")?;
    writeln!(out, "pub(super) const POSE_COUNT: usize = {POSE_COUNT};")?;
    emit(&mut out, "CALM", &calm())?;
    emit_rose(&mut out, "STAFF", &staff())?;
    emit_rose(&mut out, "PENNANT", &pennant())?;
    emit_rose(&mut out, "FULL", &full_barb())?;
    emit_rose(&mut out, "HALF", &half_barb())
}

fn emit(out: &mut impl Write, name: &str, model: &Model) -> io::Result<()> {
    emit_rust(
        out,
        name,
        &forge(model, Charge::Bronze(0.96)),
        RustReach::Module,
    )
}

fn emit_rose(out: &mut impl Write, name: &str, die: &Model) -> io::Result<()> {
    for pose in 0..POSE_COUNT {
        let angle = TAU * pose as f32 / POSE_COUNT as f32;
        let model = die.transformed(
            |point| point.rotate_z(angle),
            |normal| normal.rotate_z(angle),
        );
        emit(out, &format!("{name}_{pose:02}"), &model)?;
    }
    writeln!(
        out,
        "pub(super) static {name}: [ForgedMesh; POSE_COUNT] = ["
    )?;
    for pose in 0..POSE_COUNT {
        writeln!(out, "{name}_{pose:02},")?;
    }
    writeln!(out, "];")
}

fn staff() -> Model {
    bar([0.0, 0.0], [0.0, -32.0], 3.2)
}

fn full_barb() -> Model {
    bar([0.0, 0.0], [10.2, -6.1], 3.0)
}

fn half_barb() -> Model {
    bar([0.0, 0.0], [6.0, -3.6], 3.0)
}

fn pennant() -> Model {
    plate(&[[0.0, 0.0], [0.0, 6.0], [10.2, 0.0]])
}

fn calm() -> Model {
    const SEGMENTS: usize = 24;
    const INNER: f32 = 3.3;
    const OUTER: f32 = 6.2;
    const RISE: f32 = 0.58;
    let mut model = Model::default();
    for segment in 0..SEGMENTS {
        let a = TAU * segment as f32 / SEGMENTS as f32;
        let b = TAU * (segment + 1) as f32 / SEGMENTS as f32;
        let (sin_a, cos_a) = a.sin_cos();
        let (sin_b, cos_b) = b.sin_cos();
        let inner_a = V3::new(INNER * cos_a, INNER * sin_a, RISE);
        let inner_b = V3::new(INNER * cos_b, INNER * sin_b, RISE);
        let outer_a = V3::new(OUTER * cos_a, OUTER * sin_a, RISE);
        let outer_b = V3::new(OUTER * cos_b, OUTER * sin_b, RISE);
        model.quad([
            Vertex::new(inner_a, V3::new(0.0, 0.0, 1.0)),
            Vertex::new(outer_a, V3::new(0.0, 0.0, 1.0)),
            Vertex::new(outer_b, V3::new(0.0, 0.0, 1.0)),
            Vertex::new(inner_b, V3::new(0.0, 0.0, 1.0)),
        ]);
        let outer_normal = V3::new((cos_a + cos_b) * 0.5, (sin_a + sin_b) * 0.5, 0.0).normalized();
        model.quad([
            Vertex::new(V3::new(OUTER * cos_a, OUTER * sin_a, 0.0), outer_normal),
            Vertex::new(V3::new(OUTER * cos_b, OUTER * sin_b, 0.0), outer_normal),
            Vertex::new(outer_b, outer_normal),
            Vertex::new(outer_a, outer_normal),
        ]);
    }
    model
}

fn bar(a: [f32; 2], b: [f32; 2], width: f32) -> Model {
    let axis = [b[0] - a[0], b[1] - a[1]];
    let length = axis[0].hypot(axis[1]);
    let normal = [
        -axis[1] * width * 0.5 / length,
        axis[0] * width * 0.5 / length,
    ];
    plate(&[
        [a[0] + normal[0], a[1] + normal[1]],
        [b[0] + normal[0], b[1] + normal[1]],
        [b[0] - normal[0], b[1] - normal[1]],
        [a[0] - normal[0], a[1] - normal[1]],
    ])
}

fn plate(outline: &[[f32; 2]]) -> Model {
    const RISE: f32 = 0.58;
    const BEVEL: f32 = 0.90;
    let center = outline.iter().fold([0.0, 0.0], |sum, point| {
        [sum[0] + point[0], sum[1] + point[1]]
    });
    let center = [
        center[0] / outline.len() as f32,
        center[1] / outline.len() as f32,
    ];
    let floor = outline
        .iter()
        .map(|point| V3::new(point[0], point[1], 0.0))
        .collect::<Vec<_>>();
    let crown = outline
        .iter()
        .map(|point| {
            V3::new(
                (point[0] - center[0]).mul_add(BEVEL, center[0]),
                (point[1] - center[1]).mul_add(BEVEL, center[1]),
                RISE,
            )
        })
        .collect::<Vec<_>>();
    let mut model = Model::default();
    for edge in 0..outline.len() {
        let next = (edge + 1) % outline.len();
        let normal = (floor[next] - floor[edge])
            .cross(crown[edge] - floor[edge])
            .normalized();
        model.quad([
            Vertex::new(floor[edge], normal),
            Vertex::new(floor[next], normal),
            Vertex::new(crown[next], normal),
            Vertex::new(crown[edge], normal),
        ]);
    }
    let crown_center = Vertex::new(V3::new(center[0], center[1], RISE), V3::new(0.0, 0.0, 1.0));
    for edge in 0..outline.len() {
        let next = (edge + 1) % outline.len();
        model.triangle(
            crown_center,
            Vertex::new(crown[edge], crown_center.normal),
            Vertex::new(crown[next], crown_center.normal),
        );
    }
    model
}
